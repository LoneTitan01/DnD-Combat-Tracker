// Generates src/themes.css: the colour themes picked under Settings → Theme.
//
// The app is styled with Tailwind's stone (neutrals) and amber (accent) palettes, plus a few others for meaning
// (red damage, emerald healing, sky, violet, purple, orange). Tailwind turns every colour class into a CSS variable
// (bg-stone-900 → var(--color-stone-900)), so a theme is just a block that redefines those variables under
// [data-theme="…"]. Run `node scripts/build-themes.mjs` after changing the themes below or upgrading Tailwind.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const tw = readFileSync(`${root}node_modules/tailwindcss/theme.css`, 'utf8');

const SHADES = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
/** The palettes the app's classes use; these are the ones a theme can change. */
const NEUTRAL = 'stone';
const ACCENT = 'amber';
const SEMANTIC = ['red', 'orange', 'emerald', 'sky', 'violet', 'purple'];

const palettes = {};
for (const m of tw.matchAll(/--color-([a-z]+)-(\d+):\s*([^;]+);/g)) {
  (palettes[m[1]] ??= {})[m[2]] = m[3].trim();
}

/** Neutrals on a light theme: dark becomes light and light becomes dark. */
const invert = (s) => (s === 50 ? 950 : s === 950 ? 50 : 1000 - s);
/**
 * Colours on a light theme. Tints (950–800) and light text (400–200) swap ends; the middle shades used for solid
 * buttons are pushed darker so their white or near-white text stays readable.
 */
const LIGHT_COLOUR = { 50: 950, 100: 900, 200: 800, 300: 700, 400: 800, 500: 700, 600: 600, 700: 700, 800: 200, 900: 100, 950: 50 };

/** Each theme maps the app's palettes onto Tailwind palettes. */
const THEMES = {
  // The original look. Spelled out so a part of the page (the table screen) can force it.
  tavern: { scheme: 'dark' },
  daylight: { scheme: 'light', neutral: { from: 'stone', map: invert }, colours: LIGHT_COLOUR },
  parchment: {
    scheme: 'light',
    neutral: { from: 'taupe', map: invert },
    colours: LIGHT_COLOUR,
    extra: {
      // Cream paper rather than white: page, cards, borders.
      '--color-stone-950': 'oklch(94.5% 0.03 85)',
      '--color-stone-900': 'oklch(97.5% 0.022 88)',
      '--color-stone-800': 'oklch(87% 0.035 78)',
      '--color-stone-700': 'oklch(80% 0.04 72)',
    },
  },
  midnight: { scheme: 'dark', neutral: { from: 'slate' }, accent: 'cyan' },
  forest: { scheme: 'dark', neutral: { from: 'olive' }, accent: 'lime' },
  arcane: { scheme: 'dark', neutral: { from: 'mauve' }, accent: 'fuchsia' },
};

const value = (palette, shade) => {
  const v = palettes[palette]?.[shade];
  if (!v) throw new Error(`Tailwind has no --color-${palette}-${shade}`);
  return v;
};

let css = `/* Generated by scripts/build-themes.mjs — edit that, not this. */\n`;
for (const [id, t] of Object.entries(THEMES)) {
  const lines = [`  color-scheme: ${t.scheme};`];
  const set = (target, from, map = (s) => s) => {
    for (const s of SHADES) lines.push(`  --color-${target}-${s}: ${value(from, map(s))};`);
  };
  set(NEUTRAL, t.neutral?.from ?? NEUTRAL, t.neutral?.map);
  set(ACCENT, t.accent ?? ACCENT, t.colours && ((s) => t.colours[s]));
  for (const p of SEMANTIC) set(p, p, t.colours && ((s) => t.colours[s]));
  for (const [k, v] of Object.entries(t.extra ?? {})) {
    const i = lines.findIndex((l) => l.startsWith(`  ${k}:`));
    lines[i] = `  ${k}: ${v};`;
  }
  css += `\n[data-theme='${id}'] {\n${lines.join('\n')}\n}\n`;
}

writeFileSync(`${root}src/themes.css`, css);
console.log(`Wrote src/themes.css (${Object.keys(THEMES).length} themes)`);
